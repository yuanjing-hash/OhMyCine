import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { normalizeLineEndings } from './line-endings.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const catalog = JSON.parse(await readFile(resolve(root, '../internal/authz/catalog.json'), 'utf8'))
const propertyName = code => code.split(/[._-]/).map(part => part[0].toUpperCase() + part.slice(1)).join('')
if (!Array.isArray(catalog)) throw new Error('permission catalog must be an array')
const codes = new Set()
const properties = new Set()
for (const item of catalog) {
  if (!item || typeof item.code !== 'string' || !/^[a-z][a-z0-9_.-]*$/.test(item.code)) throw new Error('permission catalog contains an invalid code')
  if (codes.has(item.code)) throw new Error(`duplicate permission code: ${item.code}`)
  const property = propertyName(item.code)
  if (properties.has(property)) throw new Error(`generated permission property collision: ${property}`)
  codes.add(item.code); properties.add(property)
}
const lines = catalog.map(item => `  ${propertyName(item.code)}: '${item.code}',`)
const output = `// Code generated by scripts/generate-permissions.mjs; DO NOT EDIT.\nexport const Permissions = {\n${lines.join('\n')}\n} as const\n\nexport type PermissionCode = typeof Permissions[keyof typeof Permissions]\n`
const target = resolve(root, 'src/auth/generated-permissions.ts')
if (process.argv.includes('--check')) {
  const existing = await readFile(target, 'utf8').catch(() => '')
  if (normalizeLineEndings(existing) !== output) {
    console.error('generated-permissions.ts is stale; run npm run permissions:generate')
    process.exit(1)
  }
} else {
  await writeFile(target, output)
}
